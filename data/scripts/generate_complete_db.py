def strip_tashkeel(text):
    if not text:
        return ""
    text = re.sub(r'[\u064B-\u065F\u0670\u0640\u06D6-\u06ED]', '', text)
    text = re.sub(r'[إأآٱا]', 'ا', text)
    text = re.sub(r'[يى]', 'ي', text)
    text = re.sub(r'[ةه]', 'ه', text)
    return text

