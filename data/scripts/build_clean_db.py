import sqlite3
import os

def create_database():
    db_dir = "app/src/main/assets/databases"
    os.makedirs(db_dir, exist_ok=True)
    db_path = os.path.join(db_dir, "sunnah.db")

    if os.path.exists(db_path):
        os.remove(db_path)

    print(f"Creating clean SQLite database at {db_path}...")
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    # Enable standard SQLite configurations
    cur.execute("PRAGMA page_size = 4096;")
    cur.execute("PRAGMA journal_mode = DELETE;")

    # 1. Create Hadith Table
    cur.execute("""
    CREATE TABLE Hadith (
        id INTEGER PRIMARY KEY,
        collection TEXT NOT NULL,
        book TEXT NOT NULL,
        chapter TEXT NOT NULL,
        hadithNumber INTEGER NOT NULL,
        narrator TEXT NOT NULL,
        arabicText TEXT NOT NULL,
        sourceReference TEXT NOT NULL,
        authenticity TEXT NOT NULL,
        isAgreedUpon INTEGER NOT NULL,
        linkedHadithId INTEGER,
        rawId INTEGER NOT NULL,
        chapterId INTEGER NOT NULL,
        bookId INTEGER NOT NULL
    );
    """)

    # 2. Create Sunnah Table
    cur.execute("""
    CREATE TABLE Sunnah (
        id INTEGER PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT NOT NULL,
        hadithId INTEGER NOT NULL,
        difficulty INTEGER NOT NULL,
        category TEXT NOT NULL,
        estimatedMinutes INTEGER NOT NULL,
        orderIndex INTEGER NOT NULL,
        isActive INTEGER NOT NULL
    );
    """)

    # 3. Create UserProgress Table
    cur.execute("""
    CREATE TABLE UserProgress (
        id INTEGER PRIMARY KEY,
        currentSunnahId INTEGER NOT NULL,
        completedSunnahs TEXT NOT NULL,
        currentStreak INTEGER NOT NULL,
        longestStreak INTEGER NOT NULL,
        lastCompletedDate TEXT,
        startedDate TEXT NOT NULL
    );
    """)

    # 4. Create PdfBook Table
    cur.execute("""
    CREATE TABLE PdfBook (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        title TEXT NOT NULL,
        description TEXT NOT NULL,
        filename TEXT NOT NULL,
        size INTEGER NOT NULL,
        addedDate INTEGER NOT NULL,
        isBuiltin INTEGER NOT NULL
    );
    """)

    # 5. Create HadithFts Table
    cur.execute("""
    CREATE VIRTUAL TABLE HadithFts USING fts4(
        content="Hadith",
        arabicText,
        narrator,
        book,
        chapter,
        sourceReference
    );
    """)

    # 6. Room Master Table
    cur.execute("""
    CREATE TABLE IF NOT EXISTS room_master_table (
        id INTEGER PRIMARY KEY,
        identity_hash TEXT
    );
    """)
