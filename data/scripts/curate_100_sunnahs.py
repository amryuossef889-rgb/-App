def find_hadith(cur, search_phrase, collection=None):
    # Try exact or partial like match
    query = "SELECT id, collection, arabicText, sourceReference FROM Hadith WHERE arabicText LIKE ?"
    params = [f"%{search_phrase}%"]
    if collection:
        query += " AND collection = ?"
        params.append(collection)
    query += " LIMIT 1"
    cur.execute(query, params)
    res = cur.fetchone()
    if res:
        return res[0]
    return None

